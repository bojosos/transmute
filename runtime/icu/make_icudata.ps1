# Writes the C source of a minimal ICU common-data package (the U_ICUDATA_ENTRY_POINT symbol, here
# icudt79_dat) holding only the data items the guest libicucore's exports need. Called by
# scripts/build_alchemy_icu.ps1. The format is ICU's documented common-data layout: a 32-byte data
# header (MappedData and UDataInfo, format "CmnD" version 1, little-endian, ASCII), then a table of
# contents (item count, then a name offset and a data offset per item, both relative to the table),
# the item names, and the items, each aligned to 16 bytes. The items are upstream's prebuilt files
# from third_party/icu/source/data/in, copied byte for byte.
param(
    [Parameter(Mandatory)][string]$Output,
    [Parameter(Mandatory)][string]$DataDirectory,
    [Parameter(Mandatory)][string]$Package,      # e.g. icudt79l
    [Parameter(Mandatory)][string]$Symbol,       # e.g. icudt79_dat
    [Parameter(Mandatory)][string[]]$Items       # e.g. uts46.nrm
)
$ErrorActionPreference = 'Stop'
function Align([int]$value) { ($value + 15) -band -16 }

$names = @($Items | Sort-Object { $_ } -Culture ([Globalization.CultureInfo]::InvariantCulture) |
    ForEach-Object { "$Package/$_" })   # sorted: ICU searches the table by binary search
$tableSize = 4 + 8 * $names.Count
$nameBytes = New-Object System.Collections.Generic.List[byte]
$nameOffsets = @()
foreach ($name in $names) {
    $nameOffsets += $tableSize + $nameBytes.Count
    $nameBytes.AddRange([Text.Encoding]::ASCII.GetBytes($name))
    $nameBytes.Add(0)
}
$blob = New-Object System.Collections.Generic.List[byte]
# MappedData: headerSize 32, magic 0xda 0x27; UDataInfo: size 20, reserved, little-endian, ASCII
# family, sizeof(UChar) 2, reserved, "CmnD", format version 1.0.0.0, data version 0.
$blob.AddRange([byte[]](32, 0, 0xda, 0x27, 20, 0, 0, 0, 0, 0, 2, 0, 0x43, 0x6d, 0x6e, 0x44, 1, 0, 0, 0, 0, 0, 0, 0))
while ($blob.Count -lt 32) { $blob.Add(0) }
$table = 32
$dataOffset = Align ($tableSize + $nameBytes.Count)
$contents = @()
foreach ($item in ($names | ForEach-Object { $_.Substring($Package.Length + 1) })) {
    $bytes = [IO.File]::ReadAllBytes((Join-Path $DataDirectory $item))
    $contents += , @($dataOffset, $bytes)
    $dataOffset = Align ($dataOffset + $bytes.Length)
}
$blob.AddRange([BitConverter]::GetBytes([uint32]$names.Count))
for ($index = 0; $index -lt $names.Count; ++$index) {
    $blob.AddRange([BitConverter]::GetBytes([uint32]$nameOffsets[$index]))
    $blob.AddRange([BitConverter]::GetBytes([uint32]$contents[$index][0]))
}
$blob.AddRange($nameBytes)
foreach ($entry in $contents) {
    while ($blob.Count -lt $table + $entry[0]) { $blob.Add(0) }
    $blob.AddRange([byte[]]$entry[1])
}
while ($blob.Count % 16) { $blob.Add(0) }

$text = New-Object Text.StringBuilder
[void]$text.AppendLine("/* Generated by runtime/icu/make_icudata.ps1: ICU common data ($Package) with $($Items -join ', '). */")
[void]$text.AppendLine("const unsigned char $Symbol[$($blob.Count)] __attribute__((aligned(16))) = {")
for ($offset = 0; $offset -lt $blob.Count; $offset += 16) {
    $row = @($blob.GetRange($offset, [Math]::Min(16, $blob.Count - $offset)) | ForEach-Object { '0x{0:x2}' -f $_ })
    [void]$text.AppendLine('    ' + ($row -join ', ') + ',')
}
[void]$text.AppendLine('};')
[IO.File]::WriteAllText($Output, $text.ToString())
