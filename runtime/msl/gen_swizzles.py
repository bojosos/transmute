#!/usr/bin/env python3
# Generates runtime/msl/__msl/swizzle{2,3,4}.inc: the vector swizzle members of
# metal::vec<T, N> (project-authored, MIT). Each swizzle is an MSVC-style
# property (clang -fms-extensions) backed by a getter and, when no component
# repeats, a setter. Run from any directory; the files are committed.
import itertools
import pathlib

SETS = ("xyzw", "rgba")


def emit(n):
    lines = [f"// Generated by gen_swizzles.py: swizzles of a {n}-component vector. Do not edit.\n"]
    for names in SETS:
        letters = names[:n]
        for length in range(1, 5):
            for combo in itertools.product(range(n), repeat=length):
                name = "".join(letters[i] for i in combo)
                indices = ",".join(str(i) for i in combo)
                writable = len(set(combo)) == length
                macro = f"__MSL_SWZ{length}{'W' if writable else 'R'}"
                lines.append(f"{macro}({name},{indices})\n")
    return "".join(lines)


def main():
    out = pathlib.Path(__file__).resolve().parent / "__msl"
    out.mkdir(exist_ok=True)
    for n in (2, 3, 4):
        (out / f"swizzle{n}.inc").write_text(emit(n), newline="\n")


if __name__ == "__main__":
    main()
