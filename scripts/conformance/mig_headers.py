"""Generates the user-side MIG headers (mach/task.h, mach/mach_port.h, ...) from xnu's .defs files.

xnu's install runs MIG (bootstrap_cmds) for these, which is not among the downloaded projects. Test
programs only need the prototypes, which follow MIG's user-side calling convention:

    in scalar or port        T name                 out/inout scalar     T *name
    in struct[N]             T name                 out/inout struct     T *name
    array[N] (fixed)         T name
    array[*:N] (inline)      in: T name, mach_msg_type_number_t nameCnt
                             out/inout: T name, mach_msg_type_number_t *nameCnt
    array[] / ^array[]       in: T name, mach_msg_type_number_t nameCnt
                             out/inout: T *name, mach_msg_type_number_t *nameCnt
    polymorphic              in: mach_port_t name, mach_msg_type_name_t namePoly (out: pointers)

SameCount arrays share the previous array's count. Server-only arguments (MsgSeqno,
ServerAuditToken, ServerSecToken, sreplyport) are dropped. T is the type's cusertype, else its ctype,
else its own name. UserPrefix is ignored: the installed headers declare the plain names.
"""
import re
import subprocess

USER_HEADERS = ["clock", "clock_priv", "host_priv", "host_security", "mach_host", "mach_port", "mach_vm",
                "mach_voucher", "mach_voucher_attr_control", "memory_entry", "processor", "processor_set",
                "task", "thread_act", "vm_map"]
SERVER_ONLY = {"msgseqno", "serveraudittoken", "serversectoken", "sreplyport", "servercontext"}
DIRECTIONS = {"in", "out", "inout", "requestport", "replyport", "ureplyport", "waittime", "msgoption"} | SERVER_ONLY


class Type:
    def __init__(self, name, kind, ctype=None):
        self.name, self.kind, self.ctype = name, kind, ctype or name

    def c(self):
        return self.ctype


def parse_type_spec(name, spec, types):
    """spec: the text after '=' up to ';' (may include ctype:/cusertype:/intran: clauses)."""
    clauses = re.split(r"\b(ctype|cusertype|intran|outtran|destructor|intranpayload)\s*:", spec)
    base = clauses[0].strip()
    extra = dict(zip(clauses[1::2], (v.strip() for v in clauses[2::2])))
    ctype = extra.get("cusertype") or extra.get("ctype")
    if ctype:
        ctype = ctype.split()[0].rstrip(";")
    base = base.replace("\n", " ")
    if base.startswith("polymorphic"):
        kind = "poly"
    elif re.match(r"\^?\s*array\s*\[\s*\]", base):
        kind = "unbounded"
    elif re.match(r"array\s*\[\s*\*\s*:", base):
        kind = "inline"
    elif re.match(r"array\s*\[", base):
        kind = "fixed"
    elif re.match(r"struct\s*\[", base):
        kind = "struct"
    elif re.match(r"c_string\s*\[", base):
        kind = "string"
    else:
        ref = base.split()[0] if base.split() else ""
        kind = types[ref].kind if ref in types else "scalar"
        if ctype is None and ref in types and types[ref].kind not in ("scalar",):
            ctype = None
    return Type(name, kind, ctype)


def params(args, types):
    out = []
    for arg in args:
        arg = arg.strip()
        if not arg:
            continue
        m = re.match(r"^(?:(\w+)\s+)?(\w+)\s*:\s*([\w$]+)(.*)$", arg, re.S)
        if not m:
            raise ValueError(f"cannot parse argument {arg!r}")
        direction, name, tname, rest = m.groups()
        direction = (direction or "in").lower()
        if direction not in DIRECTIONS:
            raise ValueError(f"unknown direction {direction!r} in {arg!r}")
        if direction in SERVER_ONLY:
            continue
        flags = {f.strip().lower() for f in rest.split(",") if f.strip()}
        t = types.get(tname, Type(tname, "scalar"))
        ct = t.c()
        output = direction in ("out", "inout")
        if t.kind == "poly":
            out.append(f"{ct} {'*' if output else ''}{name}")
            out.append(f"mach_msg_type_name_t {'*' if output else ''}{name}Poly")
        elif t.kind in ("inline", "unbounded"):
            ptr = "*" if output and t.kind == "unbounded" else ""
            out.append(f"{ct} {ptr}{name}")
            if "samecount" not in flags:
                out.append(f"mach_msg_type_number_t {'*' if output else ''}{name}Cnt")
        elif t.kind in ("fixed", "string"):
            out.append(f"{ct} {name}")
        else:  # scalar, port, struct
            out.append(f"{ct} {'*' if output else ''}{name}")
    return out


def generate_all(xnu, clang, outdir):
    mach = xnu / "osfmk" / "mach"
    include_dirs = [xnu / "osfmk", xnu / "bsd", xnu / "EXTERNAL_HEADERS"]
    written = []
    for name in USER_HEADERS:
        text = (mach / f"{name}.defs").read_text(errors="replace")
        imports, routines = parse_defs(text, clang, include_dirs)
        guard = f"_{name}_user_"
        lines = [f"/* Generated by scripts/conformance/mig_headers.py from xnu osfmk/mach/{name}.defs (APSL-2.0). */",
                 f"#ifndef {guard}", f"#define {guard}", "",
                 "#include <mach/ndr.h>", "#include <mach/boolean.h>", "#include <mach/kern_return.h>",
                 "#include <mach/notify.h>", "#include <mach/mach_types.h>", "#include <mach/message.h>",
                 "#include <mach/mig_errors.h>", "#include <mach/port.h>"]
        lines += [f"#include {i}" for i in imports]
        lines += ["", "#ifdef __cplusplus", "extern \"C\" {", "#endif", ""]
        for rname, ps in routines:
            lines.append(f"kern_return_t {rname}({', '.join(ps) if ps else 'void'});")
        lines += ["", "#ifdef __cplusplus", "}", "#endif", f"#endif /* {guard} */", ""]
        (outdir / f"{name}.h").write_text("\n".join(lines))
        written.append((name, len(routines)))
    return written


def parse_defs(text, clang, include_dirs):
    pre = subprocess.run([str(clang), "-E", "-P", "-x", "c", "--target=arm64-apple-macos11",
                          "-DLIBSYSCALL_INTERFACE=1", *[f"-I{d}" for d in include_dirs], "-"],
                         input=text, check=True, capture_output=True, text=True).stdout
    pre = re.sub(r"/\*.*?\*/|//[^\n]*", "", pre, flags=re.S)
    types = {p: Type(p, "scalar") for p in re.findall(r"\bMACH_MSG_TYPE_\w+", pre)}
    imports, routines = [], []
    pos = 0
    statement = re.compile(r"\s*(simpleroutine|routine)\s+(\w+)\s*\((.*?)\)\s*;|\s*([^;]*);", re.S | re.I)
    while pos < len(pre):
        m = statement.match(pre, pos)
        if not m:
            # Skip an unparseable fragment up to the next ';'.
            nxt = pre.find(";", pos)
            pos = len(pre) if nxt < 0 else nxt + 1
            continue
        pos = m.end()
        if m.group(1):
            routines.append((m.group(2), params(m.group(3).split(";"), types)))
            continue
        stmt = (m.group(4) or "").strip()
        t = re.match(r"^type\s+(\w+)\s*=\s*(.*)$", stmt, re.S)
        if t:
            types[t.group(1)] = parse_type_spec(t.group(1), t.group(2), types)
            continue
        i = re.match(r"^(u|s)?import\s+([<\"][^>\"]+[>\"])", stmt, re.I)
        if i and (i.group(1) or "").lower() != "s":
            imports.append(i.group(2))
    return imports, routines
