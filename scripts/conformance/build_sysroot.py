"""Assemble the conformance sysroot's usr/include from Apple open-source releases.

The conformance suites are compiled against Darwin's real declarations, never
against runtime/include: a wrong constant in our own headers would otherwise
agree with the same wrong constant in a provider. Every input is an extracted
upstream release under --sources (see sources.json); nothing here is vendored
and nothing from the sysroot is linked into a product. No Apple SDK is used.

Usage: python -I build_sysroot.py --sources C:\\dev\\conformance --out C:\\dev\\conformance\\out\\sysroot
"""
import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))

import mig_headers  # noqa: E402
import unifdef  # noqa: E402

import conformance  # noqa: E402

CLANG_HINTS = [d / "clang.exe" for d in conformance.llvm_hints()]


def copy_tree(src, dst, pattern="*.h", recursive=False, exclude=()):
    src = pathlib.Path(src)
    if not src.is_dir():
        raise SystemExit(f"missing header directory {src}")
    files = src.rglob(pattern) if recursive else src.glob(pattern)
    count = 0
    for f in files:
        rel = f.relative_to(src)
        if any(part in exclude for part in rel.parts) or rel.as_posix() in exclude or not f.is_file():
            continue
        out = dst / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(f, out)
        count += 1
    return count


def copy_files(src, dst, names):
    dst.mkdir(parents=True, exist_ok=True)
    for name in names:
        shutil.copyfile(pathlib.Path(src) / name, dst / pathlib.Path(name).name)


# Runs AvailabilityVersions' own script. On Windows a NamedTemporaryFile cannot be reopened while it is
# open, which the script's --preprocess does, so the wrapper makes them delete=False.
AVAILABILITY_WRAPPER = ("import functools, runpy, sys, tempfile;"
                        "tempfile.NamedTemporaryFile = functools.partial(tempfile.NamedTemporaryFile, delete=False);"
                        "sys.argv = sys.argv[1:]; runpy.run_path(sys.argv[0], run_name='__main__')")


def availability(script, *args, cwd=None):
    return subprocess.run([sys.executable, "-I", "-c", AVAILABILITY_WRAPPER, str(script), *map(str, args)],
                          check=True, capture_output=True, text=True, cwd=cwd).stdout


def macos_versions(script):
    out = availability(script, "--macosx")
    return out.split()


def symbol_aliasing(versions):
    # xnu bsd/sys/make_symbol_aliasing.sh, macOS half (iOS aliases are irrelevant here).
    lines = ["/* Generated by scripts/conformance/build_sysroot.py after xnu's make_symbol_aliasing.sh. */", ""]
    for ver in versions:
        parts = [int(p) for p in ver.split(".")] + [0, 0]
        major, minor, rel = parts[:3]
        if major < 10 or (major == 10 and minor < 10):
            value, name = f"{major}{minor}0", f"__MAC_{major}_{minor}"
        else:
            value = f"{major}{minor:02d}{rel:02d}"
            name = f"__MAC_{major}_{minor}_{rel}" if rel else f"__MAC_{major}_{minor}"
        lines += [f"#if defined(__ENVIRONMENT_MAC_OS_X_VERSION_MIN_REQUIRED__) && __ENVIRONMENT_MAC_OS_X_VERSION_MIN_REQUIRED__ >= {value}",
                  f"#define __DARWIN_ALIAS_STARTING_MAC_{name}(x) x", "#else",
                  f"#define __DARWIN_ALIAS_STARTING_MAC_{name}(x)", "#endif", ""]
    return "\n".join(lines)


def posix_availability():
    # xnu bsd/sys/make_posix_availability.sh.
    lines = ["/* Generated by scripts/conformance/build_sysroot.py after xnu's make_posix_availability.sh. */", ""]
    for value in "198808L 199009L 199209L 199309L 199506L 200112L 200809L".split():
        lines += [f"#if !defined(_DARWIN_C_SOURCE) && defined(_POSIX_C_SOURCE) && _POSIX_C_SOURCE >= {value}",
                  f"#define ___POSIX_C_DEPRECATED_STARTING_{value} __deprecated", "#else",
                  f"#define ___POSIX_C_DEPRECATED_STARTING_{value}", "#endif", ""]
    return "\n".join(lines)


def rewrite(path, fn):
    text = path.read_text(encoding="latin-1")
    fixed = fn(text)
    if fixed != text:
        path.write_text(fixed, encoding="latin-1")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sources", required=True, type=pathlib.Path)
    ap.add_argument("--out", required=True, type=pathlib.Path)
    args = ap.parse_args()
    manifest = json.loads((HERE / "sources.json").read_text())
    src = {name: args.sources / entry["dir"] / "src" for name, entry in manifest.items() if "dir" in entry}
    for name, path in src.items():
        if not path.is_dir():
            raise SystemExit(f"{name}: {path} missing; download it first (sources.json)")
    clang = next((p for p in CLANG_HINTS if p.exists()), None)
    if not clang:
        raise SystemExit("clang.exe not found (VS 2022 LLVM)")

    inc = args.out / "usr" / "include"
    if args.out.exists():
        shutil.rmtree(args.out)
    inc.mkdir(parents=True)
    work = args.out / "work"
    work.mkdir()

    # Later copies win, as in an SDK install order: kernel headers first, then the libraries.
    xnu = src["xnu"]
    copy_tree(xnu / "EXTERNAL_HEADERS" / "mach-o", inc / "mach-o", recursive=True)
    copy_tree(xnu / "EXTERNAL_HEADERS" / "architecture", inc / "architecture", recursive=True)
    copy_files(xnu / "EXTERNAL_HEADERS", inc, ["AssertMacros.h", "ptrauth.h", "ptrcheck.h"])
    copy_tree(xnu / "osfmk" / "arm", inc / "arm")
    copy_tree(xnu / "bsd" / "arm", inc / "arm")
    copy_tree(xnu / "bsd" / "machine", inc / "machine")
    copy_tree(xnu / "bsd" / "sys", inc / "sys", recursive=True)
    for sub in ("net", "netinet", "netinet6", "uuid", "vfs", "miscfs", "bsm"):
        copy_tree(xnu / "bsd" / sub, inc / sub, recursive=True)
    copy_tree(xnu / "osfmk" / "mach", inc / "mach", recursive=True)
    copy_tree(xnu / "osfmk" / "mach_debug", inc / "mach_debug")
    copy_tree(xnu / "libkern" / "libkern", inc / "libkern", recursive=True, exclude=("c++",))
    copy_tree(xnu / "libkern" / "os", inc / "os")
    copy_tree(xnu / "libsyscall" / "mach" / "mach", inc / "mach")
    copy_files(xnu / "libsyscall" / "wrappers" / "spawn", inc, ["spawn.h"])
    copy_files(xnu / "libsyscall" / "wrappers" / "libproc", inc, ["libproc.h"])
    copy_files(xnu / "libsyscall" / "wrappers" / "string", inc, ["strings.h"])
    copy_files(xnu / "libsyscall" / "wrappers", inc, ["gethostuuid.h"])
    (inc / "sys" / "_posix_availability.h").write_text(posix_availability())
    # MIG's user headers (mach/task.h, mach/mach_port.h, ...), which xnu's install generates.
    mig_headers.generate_all(xnu, clang, inc / "mach")

    # AvailabilityVersions: embed the DSL, then preprocess the templates (its own CMake steps).
    av = src["AvailabilityVersions"]
    tool = work / "availability"
    availability(av / "availability", "--preprocess", av / "availability", tool, cwd=work)
    for t in ("Availability.h", "AvailabilityInternal.h", "AvailabilityInternalLegacy.h", "AvailabilityMacros.h",
              "AvailabilityVersions.h", "os_availability.h"):
        target = inc / "os" / "availability.h" if t == "os_availability.h" else inc / t
        availability(tool, "--preprocess", av / "templates" / t, target, cwd=work)
    # The DSL lists xros only as a command alias of visionos, but newer libdispatch headers write
    # API_AVAILABLE(xros(...)); clang accepts xros as the same platform.
    with open(inc / "AvailabilityInternal.h", "a") as f:
        f.write("\n/* conformance sysroot: xros spelling of visionos (build_sysroot.py) */\n"
                "#ifndef __API_AVAILABLE_PLATFORM_xros\n"
                "#define __API_AVAILABLE_PLATFORM_xros(x) xros,introduced=x\n"
                "#define __API_DEPRECATED_PLATFORM_xros(x,y) xros,introduced=x,deprecated=y\n"
                "#define __API_OBSOLETED_PLATFORM_xros(x,y,z) xros,introduced=x,deprecated=y,obsoleted=z\n"
                "#define __API_UNAVAILABLE_PLATFORM_xros xros,unavailable\n"
                "#endif\n")
    (inc / "sys" / "_symbol_aliasing.h").write_text(symbol_aliasing(macos_versions(tool)))

    libc = src["Libc"]
    # Libc's xcodescripts/headers.sh: include/ minus its build-only sys/cdefs.h wrapper, plus a few
    # headers from the sources. strip-header.ed deletes the //Begin-Libc ... //End-Libc blocks
    # (Libc-internal includes); its unifdef step runs below with the xnu one.
    copy_tree(libc / "include", inc, recursive=True, exclude=("FreeBSD", "NetBSD", "sys/cdefs.h"))
    copy_files(libc, inc, ["include/FreeBSD/nl_types.h", "include/NetBSD/utmpx.h", "stdtime/FreeBSD/tzfile.h",
                           "gen/execinfo.h", "gen/get_compat.h"])
    for header in inc.rglob("*.h"):
        rewrite(header, lambda text: re.sub(r"(?m)^//Begin-Libc\n(?:.*\n)*?//End-Libc\n", "", text))
    copy_files(libc / "os", inc / "os", ["api.h", "assumes.h"])

    copy_tree(src["libplatform"] / "include", inc, recursive=True, exclude=("exclavekit",))
    pthread = src["libpthread"] / "include"
    copy_tree(pthread, inc, recursive=True)
    copy_files(pthread / "pthread", inc, ["pthread.h", "pthread_impl.h", "pthread_spis.h", "sched.h"])
    copy_tree(src["libmalloc"] / "include" / "malloc", inc / "malloc")

    info = src["Libinfo"]
    copy_files(info / "lookup.subproj", inc, ["aliasdb.h", "bootparams.h", "grp.h", "netdb.h", "netdb_async.h", "printerdb.h", "pwd.h"])
    copy_files(info / "gen.subproj", inc, ["ifaddrs.h"])
    copy_files(info / "membership.subproj", inc, ["membership.h", "ntsid.h"])
    copy_tree(info / "rpc.subproj", inc / "rpc")

    copy_files(src["libclosure"], inc, ["Block.h"])
    dispatch = src["libdispatch"]
    copy_tree(dispatch / "dispatch", inc / "dispatch")
    copy_files(dispatch / "os", inc / "os", ["object.h", "clock.h", "workgroup.h", "workgroup_base.h",
                                             "workgroup_interval.h", "workgroup_object.h", "workgroup_parallel.h"])
    objc = src["objc4"] / "runtime"
    copy_files(objc, inc / "objc", ["NSObjCRuntime.h", "NSObject.h", "Object.h", "Protocol.h", "hashtable.h",
                                    "hashtable2.h", "message.h", "objc-api.h", "objc-auto.h", "objc-class.h",
                                    "objc-exception.h", "objc-load.h", "objc-runtime.h", "objc-sync.h", "objc.h",
                                    "runtime.h"])

    # Libm's last open-source release predates arm64. Its unified Intel math.h declares the same C99
    # interface (fpclassify dispatches on sizeof, and long double is double on arm64). fenv.h is
    # architecture-specific, so the AArch64 one comes from include/ next to this script.
    copy_files(src["Libm"] / "Source" / "Intel", inc, ["math.h"])
    copy_files(src["Libm"] / "Source", inc, ["complex.h"])
    # Its complex.h stops at an unknown architecture; arm64's long double is double, as on 32-bit arm.
    rewrite(inc / "complex.h", lambda text: text.replace("#elif defined(__arm__)\n",
                                                         "#elif defined(__arm__) || defined(__arm64__)\n", 1))
    copy_tree(HERE / "include", inc, recursive=True)
    # TargetConditionals.h belongs to no open-source project, and dlfcn.h is dyld's, which is not among
    # the downloaded projects; Alchemy's own (MIT) declare the same arm64 macOS interface (RTLD_* values
    # as in dlopen(3)).
    copy_files(REPO / "runtime" / "include", inc, ["TargetConditionals.h", "dlfcn.h"])

    # The installs' unifdef passes: xnu's DATA_UNIFDEF for macOS (selects the MacOSX branches and drops
    # kernel and private sections) and Libc's generate_features.pl set. Their macros are disjoint, and
    # every other macro is left to the compiler.
    defined = {**unifdef.XNU_DEFINED, **unifdef.LIBC_DEFINED}
    undefined = unifdef.XNU_UNDEFINED | unifdef.LIBC_UNDEFINED
    for header in inc.rglob("*.h"):
        rewrite(header, lambda text: unifdef.unifdef(text, defined, undefined))

    # Link-only interfaces with the real install names and no exports: test programs link with
    # -undefined dynamic_lookup and Alchemy's providers supply every name at run time.
    lib = args.out / "usr" / "lib"
    lib.mkdir(parents=True)
    frameworks = args.out / "System" / "Library" / "Frameworks"
    for path, install_name in (
            (lib / "libSystem.tbd", "/usr/lib/libSystem.B.dylib"),
            (lib / "libobjc.tbd", "/usr/lib/libobjc.A.dylib"),
            (lib / "libm.tbd", "/usr/lib/libSystem.B.dylib"),
            (lib / "libpthread.tbd", "/usr/lib/libSystem.B.dylib"),
            (frameworks / "Foundation.framework" / "Foundation.tbd",
             "/System/Library/Frameworks/Foundation.framework/Versions/C/Foundation"),
            (frameworks / "CoreFoundation.framework" / "CoreFoundation.tbd",
             "/System/Library/Frameworks/CoreFoundation.framework/Versions/A/CoreFoundation")):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("--- !tapi-tbd\ntbd-version: 4\ntargets: [ arm64-macos ]\n"
                        f"install-name: '{install_name}'\ncurrent-version: 1.0\n...\n")

    print(f"sysroot {args.out}: {sum(1 for _ in inc.rglob('*.h'))} headers")


if __name__ == "__main__":
    main()
