"""Writes gl_functions.inc, the OpenGL entry points OpenGL.framework exports, from gl_api_11.txt
(OpenGL 1.0 and 1.1) and gl_api_extra.txt (everything later, aliases).

Each entry is {name, signature, alias}: the signature is the return code, then the parameter
codes in parentheses (see gl_exports.cpp); alias names the host driver's entry point to call when
the driver lacks `name` ("" for none).

Run: python -I gl_functions.py (from this directory)."""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

CODES = {
    "GLenum": "I", "GLuint": "I", "GLbitfield": "I",
    "GLint": "i", "GLsizei": "i",
    "GLboolean": "C", "GLubyte": "C", "GLbyte": "c",
    "GLshort": "s", "GLushort": "S",
    "GLfloat": "f", "GLclampf": "f", "GLdouble": "d", "GLclampd": "d",
    "GLintptr": "p", "GLsizeiptr": "p", "GLint64": "p", "GLuint64": "p", "GLsync": "p",
}
SUFFIX_TYPES = {"b": "GLbyte", "d": "GLdouble", "f": "GLfloat", "i": "GLint", "s": "GLshort",
                "ub": "GLubyte", "ui": "GLuint", "us": "GLushort"}
MATRICES = ["2", "3", "4", "2x3", "3x2", "2x4", "4x2", "3x4", "4x3"]


def code(declaration):
    """The code of one parameter or return type declaration."""
    text = declaration.replace("const", " ").strip()
    if "*" in text:
        return "p"
    words = text.split()
    if not words:
        raise ValueError("empty declaration")
    if words[0] == "void":
        return "v"
    if words[0] not in CODES:
        raise ValueError("unknown type " + words[0])
    return CODES[words[0]]


def parse(prototype):
    m = re.match(r"^\s*(.+?)\s*\b(gl\w+)\s*\((.*)\)\s*;?\s*$", prototype)
    if not m:
        raise ValueError("not a prototype: " + prototype)
    result, name, params = m.group(1), m.group(2), m.group(3).strip()
    ret = code(result)
    args = ""
    if params and params != "void":
        args = "".join(code(p) for p in params.split(","))
    return name, ret + "(" + args + ")"


def family(line):
    """`family NAME(PREFIX) COUNTS TYPE...` expanded to prototypes."""
    m = re.match(r"^family\s+(\w+)\((.*?)\)\s*(.*)$", line)
    base, prefix, rest = m.group(1), m.group(2).strip(), m.group(3).split()
    lead = (prefix + ", ") if prefix else ""
    out = []
    if base == "glProgramUniformMatrix":
        for t in rest:
            gl = SUFFIX_TYPES[t]
            for shape in MATRICES:
                out.append("void glProgramUniformMatrix%s%sv(GLuint program, GLint location, GLsizei count, GLboolean transpose, const %s *value)" % (shape, t, gl))
        return out
    counts, types = rest[0], rest[1:]
    for n in counts:
        for t in types:
            gl = SUFFIX_TYPES[t]
            if base in ("glUniformv", "glProgramUniformv"):
                name = base[:-1] + n + t + "v"
                out.append("void %s(%sGLsizei count, const %s *value)" % (name, lead, gl))
                continue
            name = base + n + t
            coords = ", ".join("%s %s" % (gl, "xyzw"[i]) for i in range(int(n)))
            out.append("void %s(%s%s)" % (name, lead, coords))
            if base not in ("glUniform", "glProgramUniform"):
                out.append("void %sv(%sconst %s *v)" % (name, lead, gl))
    return out


def main():
    entries = {}
    order = []

    def add(name, signature, alias=""):
        if name in entries:
            if entries[name] != (signature, alias):
                raise ValueError("conflicting entries for " + name)
            return
        entries[name] = (signature, alias)
        order.append(name)

    for line in open(os.path.join(HERE, "gl_api_11.txt"), encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#"):
            add(*parse(line))
    pending_alias_families = []
    for line in open(os.path.join(HERE, "gl_api_extra.txt"), encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("family "):
            for prototype in family(line):
                add(*parse(prototype))
        elif line.startswith("aliasfamily "):
            _, base, suffix = line.split()
            pending_alias_families.append((base, suffix))
        elif line.startswith("alias "):
            _, name, target = line.split()
            if target not in entries:
                raise ValueError("alias of unknown " + target)
            add(name, entries[target][0], target)
        else:
            add(*parse(line))
    for base, suffix in pending_alias_families:
        for name in list(order):
            if name.startswith(base) and not entries[name][1] and re.match(re.escape(base) + r"\d", name):
                add(name + suffix, entries[name][0], name)
    lines = ["// Generated by gl_functions.py from gl_api_11.txt and gl_api_extra.txt. Do not edit.",
             "// {name, signature, host alias}"]
    for name in sorted(order):
        signature, alias = entries[name]
        lines.append('{"%s", "%s", "%s"},' % (name, signature, alias))
    with open(os.path.join(HERE, "gl_functions.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(len(order), "entry points")


if __name__ == "__main__":
    sys.exit(main())
